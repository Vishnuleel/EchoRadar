"""Innovation Brief Generator.

Turns a verified hypothesis into a 13-section Innovation Opportunity Blueprint. Every item is
tagged with its basis:

  SOURCED     - retrieved from a public source (URL and retrieval date are attached)
  HYPOTHESIS  - generated by NEXUS from the taxonomy and matching engine; not validated
  USER        - supplied by a company user; not independently verified

Exports: Markdown and PDF (reportlab).
"""
from __future__ import annotations

import io
from datetime import datetime

from sqlalchemy.orm import Session

from nexus.agents import opportunity_agent
from nexus.core import taxonomy as tx
from nexus.core.scoring import LABELS
from nexus.database.models import (CollaborationHypothesis, Company, FundingOpportunity, ResearchPublication,
                                   Testbed)
from nexus.utils.validators import utcnow

DISCLAIMER = ("HYPOTHESIS - NOT A CONFIRMED COLLABORATION. This blueprint was generated by NEXUS from public "
              "information. The companies have not been contacted and have not agreed to anything. Funding "
              "programmes are listed as potentially relevant; eligibility has not been checked.")


def _d(dt: datetime | None) -> str:
    return dt.strftime("%Y-%m-%d") if dt else "date not published"


def build_blueprint(s: Session, hyp: CollaborationHypothesis, now: datetime | None = None) -> dict:
    now = now or utcnow()
    companies = {cid: s.get(Company, cid) for cid in hyp.participating_companies}
    names = {cid: c.name for cid, c in companies.items()}
    concept = tx.CONCEPTS_BY_ID.get(hyp.concept_id or "")
    b = hyp.score_breakdown

    cap_areas, sources = [], []
    seen_src = set()

    def add_source(url, label, retrieved=None):
        if url and url not in seen_src:
            seen_src.add(url)
            sources.append({"url": url, "label": label, "retrieved_at": retrieved})

    complementarity = []
    for l in hyp.evidence:
        ca, cb = tx.CAPABILITIES[l["cap_a"]].name, tx.CAPABILITIES[l["cap_b"]].name
        item = {"text": (f"{names[l['company_a']]} stated an interest in {ca}; {names[l['company_b']]} has evidenced it."
                         if l["kind"] == "stated_interest" else
                         f"{names[l['company_a']]} ({ca}) + {names[l['company_b']]} ({cb}): {l['rationale']}."),
                "basis": "HYPOTHESIS", "strength": l["strength"], "kind": l["kind"], "evidence": []}
        for side, cid, cap in (("a", l["company_a"], ca), ("b", l["company_b"], cb)):
            ev = l.get(f"evidence_{side}")
            if ev:
                basis = "SOURCED" if ev["classification"] == "FACT" and ev["urls"] else "USER"
                item["evidence"].append({"company": names[cid], "capability": cap, "excerpt": ev["excerpt"],
                                         "urls": ev["urls"], "basis": basis})
                for u in ev["urls"]:
                    add_source(u, f"{names[cid]} - public profile evidence")
        complementarity.append(item)

    for slot in hyp.required_capabilities:
        ev = slot.get("evidence") or {}
        sourced = ev.get("classification") == "FACT" and ev.get("urls")
        cap_areas.append({"slot": slot["slot"], "company": names[slot["company"]],
                          "capability": tx.CAPABILITIES[slot["capability"]].name,
                          "confidence": slot["confidence"], "basis": "SOURCED" if sourced else ("USER" if ev else "MISSING"),
                          "excerpt": ev.get("excerpt"), "urls": ev.get("urls", [])})
        for u in ev.get("urls", []):
            add_source(u, f"{names[slot['company']]} - public profile evidence")
    if not cap_areas:  # open pair without a concept: list the capabilities in the relationships
        seen = set()
        for l in hyp.evidence:
            for cid, cap in ((l["company_a"], l["cap_a"]), (l["company_b"], l["cap_b"])):
                if (cid, cap) not in seen and not (l["kind"] == "stated_interest" and cid == l["company_a"]):
                    seen.add((cid, cap))
                    cap_areas.append({"slot": tx.ROLES[tx.CAPABILITIES[cap].role], "company": names[cid],
                                      "capability": tx.CAPABILITIES[cap].name, "confidence": None, "basis": "SOURCED"})

    # which capabilities each participant brings to this hypothesis (slots and relationships)
    brings: dict[int, set] = {cid: set() for cid in hyp.participating_companies}
    for slot in hyp.required_capabilities:
        brings.setdefault(slot["company"], set()).add(slot["capability"])
    for l in hyp.evidence:
        brings.setdefault(l["company_a"], set()).add(l["cap_a"])
        brings.setdefault(l["company_b"], set()).add(l["cap_b"])

    research = []
    for r in hyp.research_ids:
        row = s.get(ResearchPublication, r["id"])
        if row:
            shared = set(r["shared_capabilities"])
            supports = [names[cid] for cid in hyp.participating_companies if brings.get(cid, set()) & shared]
            research.append({"title": row.title, "authors": ", ".join(row.authors[:4]) + (" et al." if len(row.authors) > 4 else ""),
                             "date": _d(row.publication_date), "venue": row.venue, "url": row.source_url,
                             "relevance": r["relevance"], "basis": "SOURCED", "retrieved_at": row.retrieved_at,
                             "why": ", ".join(tx.CAPABILITIES[c].name for c in r["shared_capabilities"][:3]),
                             # a paper can support one side of a connection without supporting the connection itself
                             "supports": supports,
                             "not_covered": [names[cid] for cid in hyp.participating_companies if names[cid] not in supports]})
            add_source(row.source_url, f"OpenAlex: {row.title[:70]}", row.retrieved_at)
    funding = []
    for f in hyp.funding_ids:
        row = s.get(FundingOpportunity, f["id"])
        if row:
            status = opportunity_agent.current_status(row, now)
            if status == "closed":
                continue  # never present a closed call as a current opportunity
            funding.append({"title": row.title, "status": status, "deadline": _d(row.deadline),
                            "opens": _d(row.opens_at), "url": row.source_url, "apply_url": row.apply_url,
                            "eligibility": row.eligibility, "terms": row.funding_terms, "relevance": f["relevance"],
                            "basis": "SOURCED", "retrieved_at": row.retrieved_at,
                            "note": "Potentially relevant. Eligibility NOT checked by NEXUS."})
            add_source(row.source_url, f"Vinnova open data: {row.title[:70]}", row.retrieved_at)
    testbeds = []
    for t in hyp.testbed_ids:
        row = s.get(Testbed, t["id"])
        if row:
            testbeds.append({"name": row.name, "description": row.description[:500], "url": row.source_url,
                             "kind": row.kind, "basis": "SOURCED", "retrieved_at": row.retrieved_at,
                             "note": "Access conditions are not published; ask the operator."})
            add_source(row.source_url, row.name, row.retrieved_at)

    primary = hyp.evidence[0] if hyp.evidence else None
    if concept:
        problem, experiment = concept.problem, concept.first_experiment
        requirements, risks = list(concept.technical_requirements), list(concept.risks)
    else:
        domain = tx.DOMAINS.get(b.get("domain") or "", "the shared application area")
        problem = (f"Open question: is there a customer problem in {domain.lower()} that needs both capabilities "
                   f"together? NEXUS found a technical relationship, not a validated problem.")
        experiment = ("Hold a 60-minute technical exchange where each company shows one concrete case, then "
                      "decide whether one small joint test is worth doing.")
        requirements = sorted({tx.CAPABILITIES[c].name for l in hyp.evidence[:3] for c in (l["cap_a"], l["cap_b"])})
        risks = ["No validated customer problem yet"]

    next_steps = [
        "Ask Blue Science Park to check interest with each company before any introduction is made.",
        "Validate the capability claims with the companies (the public text may be outdated or incomplete).",
    ]
    if hyp.missing_capabilities:
        next_steps.append("Identify a partner for the missing capability: " + ", ".join(hyp.missing_capabilities) + ".")
    if funding:
        f0 = funding[0]
        next_steps.append(f"Read the call text for \"{f0['title'][:70]}\" (status: {f0['status']}, deadline "
                          f"{f0['deadline']}) and check eligibility.")
    if testbeds:
        next_steps.append(f"Contact {testbeds[0]['name'].split(':')[0]} about test possibilities.")
    next_steps.append("Agree on the first experiment below and what result would justify continuing.")

    return {
        "key": hyp.key, "generated_at": now, "disclaimer": DISCLAIMER, "validation_status": hyp.validation_status,
        "title": hyp.title, "title_basis": "HYPOTHESIS",
        "problem": {"text": problem, "basis": "HYPOTHESIS"},
        "proposed_application": {"text": hyp.proposed_application, "basis": "HYPOTHESIS"},
        "capability_areas": cap_areas,
        "companies": [{"name": c.name, "website": c.website, "directory_url": c.directory_url,
                       "description": c.description, "basis": "SOURCED"} for c in companies.values()],
        "complementarity": complementarity,
        "research": research, "funding": funding, "testbeds": testbeds,
        "first_experiment": {"text": experiment, "basis": "HYPOTHESIS"},
        "technical_requirements": [{"text": r, "basis": "HYPOTHESIS"} for r in requirements],
        "missing_capabilities": list(hyp.missing_capabilities),
        "risks": [{"text": r, "basis": "HYPOTHESIS"} for r in risks] + [{"text": u, "basis": "HYPOTHESIS"} for u in hyp.uncertainty],
        "sources": sources, "next_steps": next_steps,
        "score": {"final": hyp.score, **{k: b.get(k) for k in LABELS}, "coverage": b.get("coverage"),
                  "missing": b.get("missing", []), "weights": b.get("weights", {})},
        "verification": hyp.verification, "primary_link": primary,
    }


def to_markdown(bp: dict) -> str:
    L = [f"# Innovation Opportunity Blueprint", f"## {bp['title']}", "",
         f"> **{bp['disclaimer']}**", "",
         f"Generated {bp['generated_at']:%Y-%m-%d %H:%M} UTC by NEXUS. Labels: `[SOURCED]` retrieved from a public "
         f"source, `[HYPOTHESIS]` generated by NEXUS, `[USER]` user-supplied.", ""]
    sc = bp["score"]
    L += ["### Score (strength of fit and evidence, not probability of success)",
          f"**{sc['final']:.1f} / 100** - data coverage {sc['coverage'] * 100:.0f}% of score components", ""]
    L += ["| Component | Score | Weight |", "|---|---|---|"]
    for k, label in LABELS.items():
        v = sc.get(k)
        L.append(f"| {label} | {'no data' if v is None else f'{v:.0f}'} | {sc['weights'].get(k, 0):.2f} |")
    L += ["", "### 1. Proposed innovation `[HYPOTHESIS]`", bp["title"] + ". " + bp["proposed_application"]["text"], "",
          "### 2. Problem being addressed `[HYPOTHESIS]`", bp["problem"]["text"], "",
          "### 3. Participating capability areas"]
    for a in bp["capability_areas"]:
        L.append(f"- **{a['slot']}**: {a['capability']} - {a['company']} `[{a['basis']}]`")
        if a.get("excerpt"):
            L.append(f"  - \"{a['excerpt'][:240]}\" " + (" ".join(f"[source]({u})" for u in a["urls"]) or "no public source"))
    L += ["", "### 4. Potential participating companies `[SOURCED]`"]
    L += [f"- **{c['name']}** - {c['description'] or ''} ([directory]({c['directory_url']})"
          + (f", [website]({c['website']})" if c["website"] else "") + ")" for c in bp["companies"]]
    L += ["", "### 5. Why the capabilities complement each other"]
    for c in bp["complementarity"]:
        L.append(f"- {c['text']} `[HYPOTHESIS]` (relationship strength {c['strength']:.2f}, {c['kind']})")
        for e in c["evidence"]:
            urls = " ".join(f"[source]({u})" for u in e["urls"]) or "no public source"
            L.append(f"  - {e['company']} / {e['capability']}: \"{e['excerpt'][:240]}\" `[{e['basis']}]` {urls}")
    L += ["", "### 6. Relevant research `[SOURCED: OpenAlex]`"]
    L += [f"- [{r['title']}]({r['url']}) - {r['authors']} ({r['date']}). Relevance {r['relevance']:.0f}/100. "
          f"Relates to the contribution of: {', '.join(r.get('supports') or []) or 'no participant directly'}"
          + (f"; not to {', '.join(r['not_covered'])}" if r.get("not_covered") else "") + "."
          for r in bp["research"]] or ["- No clearly relevant research record was retrieved."]
    L += ["", "### 7. Potential funding opportunities `[SOURCED: Vinnova open data]`",
          "_Potentially relevant only. Eligibility has not been checked._"]
    for f in bp["funding"]:
        L.append(f"- [{f['title']}]({f['url']}) - status **{f['status']}**, deadline {f['deadline']}. "
                 f"Relevance {f['relevance']:.0f}/100.")
        if f["eligibility"]:
            L.append(f"  - Who can apply (Vinnova's text): {f['eligibility']}")
    if not bp["funding"]:
        L.append("- No currently open or upcoming call was clearly relevant.")
    L += ["", "### 8. Possible test environments `[SOURCED]`"]
    L += [f"- [{t['name']}]({t['url']}) - \"{t['description'][:260]}\" {t['note']}" for t in bp["testbeds"]] \
        or ["- No test environment matched."]
    L += ["", "### 9. Proposed first experiment `[HYPOTHESIS]`", bp["first_experiment"]["text"], "",
          "### 10. Technical requirements `[HYPOTHESIS]`"]
    L += [f"- {r['text']}" for r in bp["technical_requirements"]]
    L += ["", "### 11. Risks, unknowns and missing capabilities"]
    if bp["missing_capabilities"]:
        L.append("- **Missing capabilities:** " + ", ".join(bp["missing_capabilities"]))
    L += [f"- {r['text']}" for r in bp["risks"]]
    L += ["", "### 12. Sources and evidence"]
    L += [f"- {x['label']}: {x['url']}" + (f" (retrieved {x['retrieved_at']:%Y-%m-%d})" if x.get("retrieved_at") else "")
          for x in bp["sources"]]
    L += ["", "### 13. Suggested next steps"]
    L += [f"{i}. {x}" for i, x in enumerate(bp["next_steps"], 1)]
    v = bp["verification"]
    L += ["", f"---\nVerification Agent: **{v.get('status')}** - {v.get('checks', {}).get('claims_with_source', 0)} of "
              f"{v.get('checks', {}).get('claims_used', 0)} capability claims have a public source."]
    return "\n".join(L)


def to_pdf(bp: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    from xml.sax.saxutils import escape as esc

    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], fontSize=18, textColor=colors.HexColor("#0B2545"), alignment=0)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=12, textColor=colors.HexColor("#13538A"), spaceBefore=10)
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("small", parent=body, fontSize=8, textColor=colors.HexColor("#444444"))
    warn = ParagraphStyle("warn", parent=body, backColor=colors.HexColor("#FFF4D6"), borderPadding=6, fontSize=9)

    def link(url, text=None):
        return f'<link href="{esc(url)}" color="#13538A">{esc(text or url)}</link>'

    story = [Paragraph("Innovation Opportunity Blueprint", small), Paragraph(esc(bp["title"]), h1),
             Paragraph(esc(bp["disclaimer"]), warn), Spacer(1, 6),
             Paragraph(f"Generated {bp['generated_at']:%Y-%m-%d %H:%M} UTC by NEXUS. [SOURCED] = public source, "
                       f"[HYPOTHESIS] = generated by NEXUS, [USER] = user-supplied.", small)]
    sc = bp["score"]
    rows = [["Component", "Score", "Weight"]] + [
        [LABELS[k], "no data" if sc.get(k) is None else f"{sc[k]:.0f}", f"{sc['weights'].get(k, 0):.2f}"] for k in LABELS
    ] + [["Final score (fit and evidence, not success probability)", f"{sc['final']:.1f}", f"coverage {sc['coverage'] * 100:.0f}%"]]
    t = Table(rows, colWidths=[95 * mm, 30 * mm, 35 * mm])
    t.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8.5), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0B2545")),
                           ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("GRID", (0, 0), (-1, -1), 0.3, colors.grey),
                           ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold")]))
    story += [Spacer(1, 6), t]

    def section(title, paras):
        story.append(Paragraph(esc(title), h2))
        for p in paras:
            story.append(Paragraph(p, body))

    section("1. Proposed innovation [HYPOTHESIS]", [esc(bp["title"] + ". " + bp["proposed_application"]["text"])])
    section("2. Problem being addressed [HYPOTHESIS]", [esc(bp["problem"]["text"])])
    section("3. Participating capability areas",
            [f"&bull; <b>{esc(a['slot'])}</b>: {esc(a['capability'])} - {esc(a['company'])} [{a['basis']}]" for a in bp["capability_areas"]])
    section("4. Potential participating companies [SOURCED]",
            [f"&bull; <b>{esc(c['name'])}</b> - {esc(c['description'] or '')} ({link(c['directory_url'], 'member directory')})" for c in bp["companies"]])
    paras = []
    for c in bp["complementarity"]:
        paras.append(f"&bull; {esc(c['text'])} [HYPOTHESIS] (strength {c['strength']:.2f})")
        for e in c["evidence"]:
            src = " ".join(link(u, "source") for u in e["urls"]) or "no public source"
            paras.append(f"&nbsp;&nbsp;&nbsp;- <i>{esc(e['company'])} / {esc(e['capability'])}</i>: \"{esc(e['excerpt'][:220])}\" [{e['basis']}] {src}")
    section("5. Why the capabilities complement each other", paras)
    section("6. Relevant research [SOURCED: OpenAlex]",
            [f"&bull; {link(r['url'], r['title'])} - {esc(r['authors'])} ({r['date']}). Relevance {r['relevance']:.0f}/100." for r in bp["research"]]
            or ["No clearly relevant research record was retrieved."])
    paras = ["<i>Potentially relevant only. Eligibility has not been checked.</i>"]
    for f in bp["funding"]:
        paras.append(f"&bull; {link(f['url'], f['title'])} - status <b>{f['status']}</b>, deadline {f['deadline']}. Relevance {f['relevance']:.0f}/100.")
        if f["eligibility"]:
            paras.append(f"&nbsp;&nbsp;&nbsp;Who can apply (Vinnova's text): {esc(f['eligibility'])}")
    if not bp["funding"]:
        paras.append("No currently open or upcoming call was clearly relevant.")
    section("7. Potential funding opportunities [SOURCED: Vinnova]", paras)
    section("8. Possible test environments [SOURCED]",
            [f"&bull; {link(t['url'], t['name'])} - \"{esc(t['description'][:240])}\" {esc(t['note'])}" for t in bp["testbeds"]] or ["No test environment matched."])
    section("9. Proposed first experiment [HYPOTHESIS]", [esc(bp["first_experiment"]["text"])])
    section("10. Technical requirements [HYPOTHESIS]", [f"&bull; {esc(r['text'])}" for r in bp["technical_requirements"]])
    section("11. Risks, unknowns and missing capabilities",
            ([f"&bull; <b>Missing capabilities:</b> {esc(', '.join(bp['missing_capabilities']))}"] if bp["missing_capabilities"] else [])
            + [f"&bull; {esc(r['text'])}" for r in bp["risks"]])
    section("12. Sources and evidence",
            [f"&bull; {esc(x['label'])}: {link(x['url'])}" + (f" (retrieved {x['retrieved_at']:%Y-%m-%d})" if x.get("retrieved_at") else "") for x in bp["sources"]])
    section("13. Suggested next steps", [f"{i}. {esc(x)}" for i, x in enumerate(bp["next_steps"], 1)])
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                      bottomMargin=16 * mm, title=f"NEXUS blueprint - {bp['title']}").build(story)
    return buf.getvalue()
